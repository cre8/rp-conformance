// `summary.md` and JUnit XML of an issuer run, next to report.json, in the form of the RP run's (harness design
// section 5): one JUnit test suite per variant, one test case per FCAF test case.
import { writeFile } from 'node:fs/promises';
import { hostname } from 'node:os';
import { parseIssuerTestCaseId } from '@eudi-pcaf/core';
import type { IssuerRunReport, IssuerTestCaseRecord } from './runner';

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** The reasons of a result that did not pass, one per line. */
const details = (record: IssuerTestCaseRecord) =>
  [record.reason, ...record.steps.filter((s) => s.verdict !== 'PASS').map((s) => `step ${s.step} (${s.expected}, fault ${s.fault ?? 'none'}): ${s.verdict}: ${s.reason}`)]
    .filter(Boolean)
    .join('\n');

export async function writeIssuerSummary(report: IssuerRunReport, path: string): Promise<void> {
  const { run } = report;
  const enrolment = run.environment.enrolment;
  const lines = [
    `# Issuer conformance run ${run.id}`,
    '',
    `Adapter \`${run.adapter}\`${run.provider ? ` (${Object.entries(run.provider).map(([k, v]) => `${k} \`${v}\``).join(', ')})` : ''}, ${run.startedAt} to ${run.finishedAt ?? ''}.`,
    ...(enrolment ? ['', `Enrolment: ${enrolment.entity}, ${enrolment.method === 'csr' ? 'from the Provider\'s CSRs' : 'keys generated by the Test Registrar'}.`] : []),
    '',
    Object.entries(run.summary).map(([verdict, count]) => `${verdict}: ${count}`).join(', ') || 'No test case ran.',
    ...(run.error ? ['', `Run error: ${run.error}`] : []),
    '',
    '| Test case | Variant | Verdict | Reason |',
    '| --- | --- | --- | --- |',
    ...report.results.map((r) => {
      const reason = [r.knownFinding && `Known finding: ${r.knownFinding}.`, r.reason ?? r.steps.map((s) => `step ${s.step}: ${s.reason}`).join('; ')].filter(Boolean).join(' ');
      return `| ${r.testCase} | ${r.variant} | ${r.verdict}${r.knownFinding ? ' (known)' : ''} | ${cell(reason)} |`;
    }),
    '',
  ];
  await writeFile(path, lines.join('\n'));
}

const xml = (value: string) =>
  value
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const seconds = (ms: number | undefined) => ((ms ?? 0) / 1000).toFixed(3);

function testCase(record: IssuerTestCaseRecord): string {
  const id = parseIssuerTestCaseId(record.testCase);
  const open = `    <testcase classname="${id.sutClass}_${id.layer}.${id.area}" name="${xml(`${record.testCase} [${record.variant}]`)}" time="${seconds(record.durationMs)}"`;
  const message = (text: string) => xml(text.split('\n')[0].slice(0, 500));
  switch (record.verdict) {
    case 'PASS':
      return `${open}/>`;
    case 'FAIL': {
      const prefix = record.knownFinding ? `known finding: ${record.knownFinding}` : 'FAIL';
      return `${open}>\n      <failure type="${record.knownFinding ? 'known-finding' : 'FAIL'}" message="${message(`${prefix}: ${details(record)}`)}">${xml(details(record))}</failure>\n    </testcase>`;
    }
    case 'NOT APPLICABLE':
      return `${open}>\n      <skipped message="${message(`NOT APPLICABLE: ${record.reason ?? ''}`)}"/>\n    </testcase>`;
    default:
      return `${open}>\n      <error type="${record.verdict}" message="${message(`${record.verdict}: ${details(record)}`)}">${xml(details(record))}</error>\n    </testcase>`;
  }
}

/** JUnit XML of an issuer run: FAIL a failure, INCONCLUSIVE and REVIEW errors, NOT APPLICABLE skipped. */
export function issuerJUnitXml(report: IssuerRunReport): string {
  const { run } = report;
  const properties = [
    ['run', run.id],
    ['sut', run.sut],
    ['adapter', run.adapter],
    ...Object.entries(run.provider ?? {}).map(([key, value]) => [`provider.${key}`, value]),
    ...(run.error ? [['run.error', run.error]] : []),
  ];
  const count = (records: IssuerTestCaseRecord[]) => ({
    tests: records.length,
    failures: records.filter((r) => r.verdict === 'FAIL').length,
    errors: records.filter((r) => r.verdict === 'INCONCLUSIVE' || r.verdict === 'REVIEW').length,
    skipped: records.filter((r) => r.verdict === 'NOT APPLICABLE').length,
    time: seconds(records.reduce((sum, r) => sum + (r.durationMs ?? 0), 0)),
  });
  const attributes = (c: ReturnType<typeof count>) => `tests="${c.tests}" failures="${c.failures}" errors="${c.errors}" skipped="${c.skipped}" time="${c.time}"`;
  const suites = [...new Set(report.results.map((r) => r.variant))].map((variant) => {
    const records = report.results.filter((r) => r.variant === variant);
    return [
      `  <testsuite name="${xml(`${run.adapter} issuer ${variant}`)}" ${attributes(count(records))} timestamp="${xml(run.startedAt)}" hostname="${xml(hostname())}">`,
      '    <properties>',
      ...properties.map(([name, value]) => `      <property name="${xml(name)}" value="${xml(value)}"/>`),
      '    </properties>',
      ...records.map(testCase),
      '  </testsuite>',
    ].join('\n');
  });
  return ['<?xml version="1.0" encoding="UTF-8"?>', `<testsuites name="${xml(`issuer-conformance ${run.id}`)}" ${attributes(count(report.results))}>`, ...suites, '</testsuites>', ''].join('\n');
}

export async function writeIssuerJUnit(report: IssuerRunReport, path: string): Promise<void> {
  await writeFile(path, issuerJUnitXml(report));
}
